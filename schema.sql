-- Dental chatbot: SQLite schema
-- Run with: sqlite3 dental.db < schema.sql
-- Every statement is IF NOT EXISTS, so it's safe to re-run on an existing database.
PRAGMA foreign_keys = ON;

-- People the bot can book for. Family members are separate rows that may share a phone.
CREATE TABLE IF NOT EXISTS patients (
  id             INTEGER PRIMARY KEY,
  full_name      TEXT NOT NULL,
  phone          TEXT NOT NULL,          -- not unique: kids share a parent's phone
  date_of_birth  TEXT NOT NULL,          -- ISO yyyy-mm-dd
  insurance_name TEXT,                   -- NULL = self-pay / no insurance
  medical_notes  TEXT,                   -- staff-entered alerts (allergies, blood thinners...). The bot never asks for or reveals this.
  created_at     TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_patients_lookup ON patients(lower(full_name), date_of_birth);

-- Fixed 1-hour slots, 8am-6pm Mon-Sat. Generated by the seed script.
CREATE TABLE IF NOT EXISTS slots (
  id         INTEGER PRIMARY KEY,
  starts_at  TEXT NOT NULL UNIQUE,       -- local time, ISO yyyy-mm-ddTHH:MM
  ends_at    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS appointments (
  id                   INTEGER PRIMARY KEY,
  patient_id           INTEGER NOT NULL REFERENCES patients(id),
  slot_id              INTEGER NOT NULL REFERENCES slots(id),
  type                 TEXT NOT NULL CHECK (type IN ('cleaning','checkup','emergency')),
  status               TEXT NOT NULL DEFAULT 'booked' CHECK (status IN ('booked','cancelled')),
  emergency_summary    TEXT,             -- short description, only for type = 'emergency'
  booked_by_patient_id INTEGER REFERENCES patients(id),  -- who made a family booking
  created_at           TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at           TEXT NOT NULL DEFAULT (datetime('now'))
);
-- The database itself prevents double-booking (cancelled rows don't count):
CREATE UNIQUE INDEX IF NOT EXISTS one_active_booking_per_slot ON appointments(slot_id) WHERE status = 'booked';
CREATE INDEX IF NOT EXISTS idx_appointments_patient ON appointments(patient_id, status);

-- One row per chat session; also holds the thumbs up/down feedback.
CREATE TABLE IF NOT EXISTS conversations (
  id         TEXT PRIMARY KEY,           -- uuid from the browser
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  rating     INTEGER CHECK (rating IN (-1, 1)),
  feedback   TEXT
);

CREATE TABLE IF NOT EXISTS messages (
  id              INTEGER PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id),
  role            TEXT NOT NULL CHECK (role IN ('user','assistant','tool')),
  content         TEXT NOT NULL,         -- JSON for tool calls/results
  created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, id);

-- What the staff page shows. Emergencies are created automatically by book_appointments.
CREATE TABLE IF NOT EXISTS staff_notifications (
  id              INTEGER PRIMARY KEY,
  kind            TEXT NOT NULL CHECK (kind IN ('emergency','escalation','callback')),
  urgency         TEXT NOT NULL CHECK (urgency IN ('normal','high')),
  summary         TEXT NOT NULL,
  patient_id      INTEGER REFERENCES patients(id),
  conversation_id TEXT REFERENCES conversations(id),
  created_at      TEXT NOT NULL DEFAULT (datetime('now')),
  acknowledged_at TEXT,                  -- NULL = not yet seen by staff
  acknowledged_by INTEGER REFERENCES staff_users(id)
);

-- Front desk accounts for the staff dashboard. Demo accounts are added by auth.ensure_staff().
CREATE TABLE IF NOT EXISTS staff_users (
  id            INTEGER PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE COLLATE NOCASE,
  full_name     TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('front_desk','admin')),
  password_hash TEXT NOT NULL,           -- scrypt$salt$hash, never the password itself
  failed_logins INTEGER NOT NULL DEFAULT 0,
  locked_until  TEXT,                    -- UTC; set after too many wrong passwords
  last_login_at TEXT,
  created_at    TEXT NOT NULL DEFAULT (datetime('now'))
);

-- One row per signed-in browser. The token is the cookie value.
CREATE TABLE IF NOT EXISTS staff_sessions (
  token      TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES staff_users(id),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  expires_at TEXT NOT NULL               -- UTC
);
